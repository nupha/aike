//! Build script for aike
//!
//! Assembles `types/aike.d.ts` from source fragments:
//! - `types/base/*.d.ts`          — always included (base types)
//! - `types/features/llama_cpp/*.d.ts` — only included when feature "llama_cpp" is enabled

use std::{env, fs, path::Path};

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR not set");
    let types_dir = Path::new(&manifest_dir).join("types");

    // --- Collect base fragments (always included) ---
    let base_dir = types_dir.join("base");
    let mut parts: Vec<(String, String)> = Vec::new();
    let mut base_entries: Vec<_> = fs::read_dir(&base_dir)
        .expect("types/base/ directory not found")
        .filter_map(|e| e.ok())
        .filter(|e| {
            let name = e.file_name();
            let s = name.to_string_lossy();
            s.ends_with(".d.ts")
        })
        .collect();
    base_entries.sort_by_key(|e| e.file_name());
    for entry in &base_entries {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().to_string();
        let content = fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("failed to read {}: {e}", path.display()));
        parts.push((name, content));
    }

    // --- Collect feature-gated fragments ---
    let feature_llama = env::var("CARGO_FEATURE_LLAMA_CPP").is_ok();
    if feature_llama {
        let feat_dir = types_dir.join("features").join("llama_cpp");
        if feat_dir.exists() {
            let mut feat_entries: Vec<_> = fs::read_dir(&feat_dir)
                .expect("types/features/llama_cpp/ directory not found")
                .filter_map(|e| e.ok())
                .filter(|e| {
                    let name = e.file_name();
                    let s = name.to_string_lossy();
                    s.ends_with(".d.ts")
                })
                .collect();
            feat_entries.sort_by_key(|e| e.file_name());
            for entry in &feat_entries {
                let path = entry.path();
                let name = entry.file_name().to_string_lossy().to_string();
                let content = fs::read_to_string(&path)
                    .unwrap_or_else(|e| panic!("failed to read {}: {e}", path.display()));
                parts.push((name, content));
            }
        }
    }

    // --- Write assembled bundle ---
    let mut bundle = String::new();
    bundle.push_str("// Auto-generated by build.rs -- DO NOT EDIT\n");
    bundle.push_str("// Sources: types/base/*.d.ts");
    if feature_llama {
        bundle.push_str(" + types/features/llama_cpp/*.d.ts");
    }
    bundle.push_str(&format!("\n// Parts: {} files\n\n", parts.len()));

    for (_name, content) in &parts {
        bundle.push_str(content);
        if !content.ends_with('\n') {
            bundle.push('\n');
        }
        bundle.push('\n');
    }

    let output = types_dir.join("aike.d.ts");
    fs::write(&output, &bundle)
        .unwrap_or_else(|e| panic!("failed to write {}: {e}", output.display()));

    eprintln!(
        "[build.rs] Generated {} ({} parts, {} bytes)",
        output.display(),
        parts.len(),
        bundle.len()
    );

    // Tell Cargo to re-run when features change (e.g. llama_cpp toggled).
    println!("cargo::rerun-if-env-changed=CARGO_FEATURE_LLAMA_CPP");

    // Watch source fragments. Also watch each directory itself so that
    // *newly added* `.d.ts` files (not yet in the per-file tracking list)
    // trigger a rebuild — otherwise a freshly added file like `mcp.d.ts`
    // would be silently omitted from the generated bundle.
    println!("cargo::rerun-if-changed={}", base_dir.display());
    for entry in &base_entries {
        println!("cargo::rerun-if-changed={}", entry.path().display());
    }
    if feature_llama {
        let feat_dir = types_dir.join("features").join("llama_cpp");
        println!("cargo::rerun-if-changed={}", feat_dir.display());
        if feat_dir.exists() {
            for entry in fs::read_dir(&feat_dir).unwrap().filter_map(|e| e.ok()) {
                println!("cargo::rerun-if-changed={}", entry.path().display());
            }
        }
    }
}
